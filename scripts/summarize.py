#!/usr/bin/env python3
"""Generate docs/results.md from principles/registry.yaml and results/.

Nothing in docs/ is written by hand. CI runs this script and fails if the committed
docs/results.md differs from what the data produce.
"""
import json, os, sys
import yaml
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import driver
import separations

ROOT = driver.ROOT
REG = yaml.safe_load(open(os.path.join(ROOT, "principles", "registry.yaml")))
NAMES = {e["id"]: e.get("name", "") for f in REG["families"] for e in f.get("entries", [])}


def load(p):
    p = os.path.join(ROOT, p)
    return [json.loads(l) for l in open(p) if l.strip()] if os.path.exists(p) else []


def pk(k):
    return frozenset(k.split(",")) if k else frozenset()


def fmt(keyset):
    return ", ".join(f"`{e}`" for e in sorted(keyset)) or "(core only)"


def main():
    q = load("results/queries.jsonl")
    replay = {r["key"]: r for r in load("results/replay.jsonl")}
    verified = {r["key"]: r for r in load("results/models_verified.jsonl")}
    certs = {r["key"]: r for r in load("results/isabelle_models.jsonl")}
    L = []
    L.append("# Results (provisional)\n")
    L.append(f"Generated by `scripts/summarize.py` from `results/` and registry {REG['registry_version']}. "
             "Do not edit by hand.\n")
    L.append("## How to read this page\n")
    L.append("A *package* is a set of registry principles, always together with factivity (FACT). "
             "Each package is classified as\n\n"
             "- **refuted**: Isabelle has checked a proof that the package is inconsistent;\n"
             "- **refuted at N1**: Isabelle has checked a proof that the package is inconsistent with "
             "N1 (at least one grounding fact), and no refutation of the package itself was found. This "
             "is not a consistency claim. Where the row says *model at N0 verified*, a model of the "
             "package in which nothing grounds anything was found by Nitpick and re-checked by the "
             "independent implementation; otherwise the package without N1 is unknown. (Until registry "
             "0.3.0-draft this class was called trivial-only and was described as consistent without a "
             "model; audit finding A3.);\n"
             "- **finite-model**: a finite model with at least one grounding fact (N1), either found by "
             "Nitpick and re-checked by an independent implementation of the semantics, or built and "
             "checked in Isabelle (`isabelle/Model_Certificates.thy`, `isabelle/Restricted_Models.thy`, "
             "`isabelle/Separation_Models.thy`, section 4);\n"
             "- **infinite-model**: an infinite model built and checked in Isabelle (decision D4);\n"
             "- every model has a certificate kind (decision D7): *nitpick+python* (found by Nitpick, re-checked "
             "by `scripts/verify_models.py`) or *isabelle-kernel* (built and proved in Isabelle). The class does "
             "not depend on the kind;\n"
             "- **unknown**: no proof and no model within the time limits. Unknown never means consistent.\n")
    L.append("A refutation of a package refutes every stronger package; a model of a package is a model "
             "of every weaker one. \"Stronger\" uses only the implications proved in "
             "`isabelle/Order.thy`. Every entry is standalone: a package contains exactly the entries "
             "listed, and an entry's rank in the registry is a label, not an inclusion.\n")

    # 1. checked puzzles
    L.append("## 1. Published puzzles, machine-checked\n")
    L.append("| Puzzle | Package | Expected | Isabelle |\n|---|---|---|---|")
    checked = {c["id"]: c for c in REG["puzzles"]["checked"]}
    for t in REG["puzzles"]["targets"]:
        # a target that names its own theorem (about the registry constants, for exactly the
        # listed package) takes precedence over the older entries under puzzles.checked
        c = t if t.get("theorem") else checked.get(t["id"], {})
        L.append(f"| {t['id']} ({t['source'].split(';')[0]}) | {fmt(t['package'])} | {t['expected'].split(';')[0]} | "
                 f"{c.get('status', REG['puzzles']['validation'].get('status', '')[:6] if t['id'] in REG['puzzles']['validation'].get('reproduced', []) else 'open')}"
                 f"{' - `' + c['theorem'] + '`' if c.get('theorem') else ''} |")
    notes = []
    for c in REG["puzzles"]["candidates"]:
        if c.get("result") and c.get("theorem"):
            L.append(f"| {c['id']} ({c['source'].split('(')[0].strip()}) | {fmt(c.get('package', []))} | refuted | "
                     f"{c['result']} (checked) - `{c['theorem']}` ({c.get('checked', '').split(':')[0].strip()}) |")
            if c.get("note"):
                notes.append(f"- {c['id']}: {c['note']}")
        elif c.get("status") == "checked":
            L.append(f"| {c['id']} ({c['source'].split('(')[0].strip()}) | {fmt(c.get('package', []))} | refuted | "
                     f"checked - {c.get('checked', '')} |")
    if notes:
        L.append("\nNotes on the rows above:\n")
        L.extend(notes)
    L.append("\nCaveat from the registry: " + REG["puzzles"]["validation"].get("caveat", "") + "\n")

    # 2. search: minimal refuted packages
    ref = [r for r in q if r["class"] in ("refuted", "refuted-at-N1")]
    def keyof(r):
        rp = replay.get(r["key"])
        return pk(rp["checked_key"]) if rp and rp.get("checked_key") is not None else pk(r["key"])
    def n0(r):
        v = verified.get(r["key"], {})
        return bool(v.get("verified")) and v.get("level") == "N0"
    refs = [(keyof(r), r["class"], bool(replay.get(r["key"], {}).get("replayed")), n0(r)) for r in ref]
    outright = [driver.closure(k) for k, c, _, _ in refs if c == "refuted"]
    mins = []
    for k, c, ok, m0 in sorted(refs, key=lambda x: len(x[0])):
        cl = driver.closure(k)
        if c == "refuted-at-N1" and any(o <= cl for o in outright):
            continue  # refuted outright by a smaller package
        if not any(driver.closure(m) <= cl and mc == c for m, mc, _, _ in mins):
            mins.append((k, c, ok, m0))
    # equal-size packages arrive in arbitrary order, so drop any entry whose closure
    # strictly contains that of another entry of the same class (or of an outright refutation)
    mins = [x for x in mins
            if not any(driver.closure(y[0]) < driver.closure(x[0]) and (y[1] == x[1] or y[1] == "refuted")
                       for y in mins)]
    L.append("## 2. Search: minimal refuted packages found so far\n")
    L.append(f"{len(q)} packages queried. Minimal refuted packages (every proper weakening tested is not refuted, "
             "or was not tested):\n")
    L.append("| Package | Class | Replayed in Isabelle |\n|---|---|---|")
    for k, c, ok, m0 in mins:
        cname = c if c == "refuted" else ("refuted at N1; model at N0 verified" if m0
                                          else "refuted at N1; without N1 unknown")
        L.append(f"| {fmt(k)} | {cname} | {'yes (`isabelle/Results_Refutations.thy`)' if ok else 'no'} |")
    L.append("")

    # 3. maximal verified models
    mods = [pk(r["key"]) for r in q if r["class"] == "finite-model" and verified.get(r["key"], {}).get("verified")]
    unver = [r["key"] for r in q if r["class"] == "finite-model" and not verified.get(r["key"], {}).get("verified")]
    maxs = [m for m in mods if not any(driver.closure(m) < driver.closure(o) for o in mods)]
    maxs = sorted(set(maxs), key=lambda m: (-len(m), sorted(m)))
    L.append("## 3. Search: largest packages with verified finite models\n")
    L.append(f"{len(mods)} verified finite models; {len(unver)} Nitpick models not (yet) re-verified. "
             "Maximal ones (no verified model of a strictly stronger package). Non-triviality: N1 only; "
             "levels N2-N5 not yet tested.\n")
    for m in maxs[:25]:
        L.append(f"- {fmt(m)}")
    if len(maxs) > 25:
        L.append(f"- ... and {len(maxs) - 25} more (see `results/queries.jsonl`)")
    L.append("")

    # 4. Isabelle-built model certificates
    L.append("## 4. Models built in Isabelle\n")
    L.append("Principles that the search left unknown on their own, because they quantify over the formula "
             "layer (where Nitpick reports only potentially spurious models) or have no finite model, and "
             "packages certified by a model built by hand. Each "
             "model is an interpretation of the signature with every constant as a parameter (locale `gsig`); "
             "`K_faithful` proves that the locale's definitions are the registry's. The infinite term model M1 "
             "(`isabelle/Models.thy`) uses the same method with a record of operations in place of the locale; "
             "its lemma `fidelity` plays the role of `K_faithful`. Each package includes "
             "FACT, and LAM_CORE when it mentions the formula layer. The models MT and MU are the "
             "models of finding F9: the puzzles that involve truth, with typed grounding of truth "
             "ascriptions, stated with the witness entries of decision D9.\n")
    if certs:
        L.append("Non-triviality levels are cumulative, and N4 counts only where CL.PROP holds (decision D8).\n")
        L.append("| Principle or package | Class | Certificate | Non-triviality | Carriers | Isabelle |\n|---|---|---|---|---|---|")
        for k in sorted(certs, key=lambda k: ("," in k, k)):
            c = certs[k]
            name = fmt(pk(k)) + " (package)" if "," in k else f"`{k}`"
            L.append(f"| {name} | {c['class']} | {c.get('certificate', '')} | {c['nontriviality']} (N3: {c['n3']}) | {c['carriers']} | "
                     f"`{c['model']}`: {c['theorems']}" + (f". {c['note']}" if c.get("note") else "") + " |")
    L.append("")

    # 5. unknowns
    sing = {r["key"]: r["class"] for r in q if "," not in r["key"]}
    unk_single = sorted(k for k, c in sing.items() if c == "unknown" and k not in certs)
    unk = [r for r in q if r["class"] == "unknown" and r["key"] not in certs]
    unk_ref = [r for r in unk if any(o <= driver.closure(pk(r["key"])) for o in outright)]
    L.append("## 5. Unknown\n")
    L.append(f"{len(unk) - len(unk_ref)} queried packages are "
             f"unknown ({len(unk_ref)} further packages that the search left unknown contain a package "
             "refuted in section 2 and are therefore refuted). Principles that are unknown even on their own (with FACT and N1): " + (fmt(unk_single) if unk_single else "none") +
             ". Section 4 resolves the principles that were unknown on their own; unknown packages that "
             "combine several principles remain.\n")

    # 6. findings
    L.append("## 6. Findings\n")
    for f in REG.get("findings", []):
        L.append(f"- **{f['id']}** ({f['status']}): {f['claim']} Proof: {f['proof'].split('.')[0]}.")
    L.append("")
    L.append("## 7. Candidate novel results\n")
    L.append("None yet. A candidate needs (a) a checked refutation from a weaker set of principles than any "
             "published puzzle uses, or (b) a verified model of a non-trivial package that no source defends, "
             "or (c) a non-classical package that escapes a published puzzle. Each will be listed here with its "
             "evidence, what would falsify it, and the literature check, kept separate from interpretation. "
             "By finding F1 most packages of interest have no finite model, so (b) and (c) wait on "
             "infinite-model certificates.\n")
    for k in sorted(certs):
        c = certs[k]
        if c.get("novelty"):
            L.append(f"- Checked and not a candidate: model `{c['model']}` ({c['theory']}). {c['novelty']}. "
                     f"Falsifiers: {c.get('falsifiers', 'none recorded')}.")
    L.append("")

    # 8. non-implications
    L.append("## 8. Entries that do not imply one another\n")
    L.append("A rank in the registry is a label. Where the registry ranks one entry above another and "
             "`isabelle/Order.thy` proves no implication, a separating model shows that there is none: "
             "the higher-ranked entry holds and the lower-ranked one fails. Models built in Isabelle are "
             "checked there. Models found by Nitpick (`scripts/separations.py`, with FACT and N1) are "
             "stored in `results/separations.jsonl` and re-checked by the independent implementation of "
             "the semantics each time this page is generated. A separating model shows a non-implication "
             "between two entries taken alone; it says nothing about packages that add further principles.\n")
    L.append("| Holds | Fails | Model | Checked |\n|---|---|---|---|")
    for sp in REG["implications"].get("separations", []):
        if sp.get("model"):
            L.append(f"| {fmt(sp['holds'])} | {fmt(sp['fails'])} | `{sp['model']}` | Isabelle: {sp['theorem']} |")
    for r in sorted(load("results/separations.jsonl"), key=lambda r: (r["holds"], r["fails"])):
        c = separations.check(r)
        card = ", ".join(f"{k} {v}" for k, v in sorted((c.get("card") or {}).items())) or "cardinality not parsed"
        L.append(f"| `{r['holds']}` | `{r['fails']}` | Nitpick, {card} | "
                 f"{'re-verified' if c['verified'] else 'NOT VERIFIED'} |")
    L.append("")
    # 9. IRR.W in place of IRR.F
    tests = REG["puzzles"].get("irr_w_tests")
    ws = load("results/woods_search.jsonl")
    if tests:
        L.append("## 9. Woods's substantive irreflexivity in place of strict irreflexivity\n")
        L.append("The Krämer and Fine targets of section 1 with `IRR.W` for `IRR.F`, the package of "
                 "Woods's Objection 3, and their union (registry, `puzzles.irr_w_tests`; findings F14-F19). "
                 "Every model is built in Isabelle (`isabelle/Woods_Models.thy`). `IRR.W` is tested with the "
                 "one-world vacuity test of decision D2, which is weaker than Woods's modal test, so a model "
                 "here does not show that his own principle is satisfied. The seven packages contain no totality "
                 "fact, and where `ALL.TOT` is added below the totality fact cannot be rewritten under "
                 "substitution, so no model here tests his own reply to Objection 5. Finding F18 assesses that "
                 "reply directly: on a stated reading of the totality fact it holds, but vacuously. Finding F19 "
                 "tests the proposal without a totality fact, in the model `MR` (`isabelle/Rule_Generated.thy`), "
                 "where propositions are structured and grounds are only what the rules generate: there `IRR.W` "
                 "fails for ∀p(p ∨ ¬p) and holds for the basic existential cases, Woods's Objection 3 among "
                 "them. `MR` is listed in section 4 as a model of the targets without any irreflexivity entry; "
                 "it is not a model of any package in the table below. The closure constraint it realises "
                 "(registry, `proposed.GEN.RULES`) is not adopted and not searched.\n")
        L.append("| Package | Entries | Status | Model |\n|---|---|---|---|")
        for t in tests["packages"]:
            L.append(f"| {t['id']} ({t['source']}) | {fmt(t['package'])} | {t['status']} | `{t['model']}` |")
        L.append("")
    if tests and ws:
        bases = [t["id"] for t in tests["packages"]]
        short = {b: b.replace("P.", "").replace("/W", "") for b in bases}
        n = {c: sum(1 for r in ws if r["class"] == c) for c in ("refuted", "finite-model", "infinite-model", "unknown")}
        L.append(f"**Search set.** {len(ws)} packages (`results/targets/woods-fine.json`, generated by "
                 "`scripts/woods_targets.py`): each package above; three controls (`IRR.F` for `IRR.W`, the "
                 "control entry `IRR.MEM` for `IRR.W`, and `ASYM.P` added); and each package with one further "
                 "registry entry added. The search ran on GitHub (Sledgehammer for refutations; Nitpick "
                 "returned no model for any package; `IRR.W` quantifies over formulas and environments, which a finite model search does not enumerate). "
                 "Classification (`scripts/woods_report.py`, `results/woods_search.jsonl`): "
                 f"{n['refuted']} refuted, {n['finite-model'] + n['infinite-model']} with a model built in Isabelle, "
                 f"{n['unknown']} unknown. A package counts as refuted only if Isabelle has checked the proof, "
                 "and as modelled only if every one of its entries follows from the entries a model record "
                 "lists. Unknown never means consistent.\n")
        lv = {}
        for r in ws:
            if r.get("nontriviality"): lv[r["nontriviality"]] = lv.get(r["nontriviality"], 0) + 1
        L.append("Models by level: " + ", ".join(f"{k} {v}" for k, v in sorted(lv.items(), reverse=True)) + ".\n")
        L.append("In the table, a cell names the model that satisfies the package, with its level when "
                 "that is below N5, or says *refuted* or *unknown*; a dash means the entry is already in "
                 "the package or cannot be combined with it (two comprehension levels). The level is that "
                 "of the model named, not the best possible. `MX` is a flat model, in which every non-empty "
                 "set of truths grounds every truth (finding F17).\n")
        rows = []
        for r in ws:
            if r["kind"] == "base":
                lab = "(the package itself)"
            elif r["kind"] in ("control", "extension"):
                lab = r["added"]
            else:
                continue
            if lab not in rows: rows.append(lab)
        cell = {}
        for r in ws:
            lab = "(the package itself)" if r["kind"] == "base" else r["added"]
            if r["kind"] == "model-check": continue
            cell[(lab, r["base"])] = ("refuted" if r["class"] == "refuted" else
                                      "unknown" if r["class"] == "unknown" else
                                      f"`{r['model']}`" + ("" if r.get("nontriviality") == "N5" else f" ({r.get('nontriviality')})"))
        L.append("| Added entry | " + " | ".join(short[b] for b in bases) + " |\n|---|" + "---|" * len(bases))
        for lab in rows:
            name = lab if lab.startswith("(") or " for " in lab else f"`{lab}`"
            L.append(f"| {name} | " + " | ".join(cell.get((lab, b), "-") for b in bases) + " |")
        L.append("")
        ref = [r for r in ws if r["class"] == "refuted"]
        if ref:
            L.append("Refutations, each checked in Isabelle:\n")
            thms = {}
            for r in ref:
                thms.setdefault(r["theorem"], []).append(r["id"])
            for th, ids in thms.items():
                L.append(f"- {th}: {', '.join(ids)}")
            L.append("")
        mc = [r for r in ws if r["kind"] == "model-check"]
        for r in mc:
            sr = r.get("search") or {}
            L.append(f"- Cross-check, {r['id']}: {fmt(pk(r['key']))}. Model `{r.get('model', 'none')}`; "
                     f"the search reported: {sr.get('class', 'not queried')}.")
        if mc: L.append("")
        unk = [r for r in ws if r["class"] == "unknown"]
        if unk:
            L.append(f"The {len(unk)} unknown packages were queried with a Sledgehammer limit of "
                     f"{max((r.get('search') or {}).get('t_sh') or 0 for r in unk)} s per prover call and no model was "
                     "built for them. Notes recorded for them: "
                     + ("; ".join(sorted({r['note'] for r in unk if r.get('note')})) or "none")
                     + ". Finding F17 says why the models above do not cover them.\n")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    open(os.path.join(ROOT, "docs", "results.md"), "w").write("\n".join(L) + "\n")
    print("wrote docs/results.md:", len(mins), "minimal refuted,", len(maxs), "maximal models")


if __name__ == "__main__":
    main()
